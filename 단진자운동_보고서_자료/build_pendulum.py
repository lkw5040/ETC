eq("F = − m g sin θ          (1)")
body("음의 부호는 힘이 변위의 반대 방향으로 작용한다는 뜻이다. 진폭이 충분히 작아 θ ≪ 1 "
     "이면 테일러 전개에 의해 sin θ ≈ θ 로 어림할 수 있고, 호의 길이가 x = l θ 이므로 "
     "식 (1)은 다음과 같이 정리된다.")
eq("m d²x/dt² = − (m g / l) x          (2)")
body("이 미분방정식의 해는 시간에 대한 코사인 함수로 주어진다.")
eq("x = x_max cos(ω t + φ)          (3)")
body("여기서 x_max 는 진폭이고, 각진동수 ω 는 다음과 같다.")
eq("ω = √(g / l)          (4)")
body("주기는 T = 2π / ω 이므로 단진자의 주기는 식 (5)가 된다.")
eq("T = 2π √(l / g)          (5)")
body("식 (5)를 중력가속도에 대해 풀면 진자의 길이와 주기로부터 g 를 구할 수 있다.")
eq("g = 4π² l / T²          (6)")
body("식 (5)에서 이 실험의 세 가지 예측이 바로 나온다. 첫째, 우변에 질량 m 이 들어 있지 "
     "않으므로 주기는 추의 질량과 무관하다. 복원력 m g sin θ 와 관성 m 이 함께 질량에 "
     "비례하여 서로 상쇄되기 때문이다. 둘째, 주기는 진폭에도 들어 있지 않으므로 진폭과 "
     "무관하다. 셋째, 주기는 길이의 제곱근에 비례한다. 식 (5)의 양변을 제곱하면")
eq("T² = (4π² / g) l          (7)")
