def make_parapr(**fmt):
    p = doc.add_paragraph("")
    doc.styles.apply_paragraph_format(paragraph_index=len(doc.paragraphs) - 1, **fmt)
    pid = p.para_pr_id_ref
    p.remove()
    return pid

